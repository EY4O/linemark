#!/usr/bin/env node
// Builds js/brand-pack.js: the brand icons (Reddit, GitHub, YouTube…) Linemark bundles for line bullets.
//
//   node tools/build-brand-pack.mjs        downloads the pinned Simple Icons release from jsDelivr
//
// Only the brands named in tools/brand-list.txt are bundled, so the extension stays small and works offline.
// Simple Icons is CC0 (public domain); its notice ships as icons/SIMPLE-ICONS-LICENSE.txt. The logos remain their
// owners' trademarks: Linemark shows one only as the icon a user picks for their own line.

import fs from 'node:fs';
import path from 'node:path';

const VERSION = '15.16.0';
const ROOT = path.resolve(import.meta.dirname, '..');
const lines = fs.readFileSync(path.join(import.meta.dirname, 'brand-list.txt'), 'utf8')
  .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));

const paths = {};
const titles = {};
const words = {};
const missing = [];
for (const line of lines) {
  const [slug, ...extra] = line.split(/\s+/);
  const res = await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`);
  if (!res.ok) { missing.push(slug); continue; }
  const svg = await res.text();
  const d = (svg.match(/<path d="([^"]+)"/) || [])[1];
  const title = (svg.match(/<title>([^<]+)<\/title>/) || [])[1];
  if (!d || !title) { missing.push(slug); continue; }
  paths[slug] = d;
  titles[slug] = title.replace(/&amp;/g, '&');
  words[slug] = [titles[slug], slug, ...extra].join(' ').toLowerCase();
}

const out = `// Generated by tools/build-brand-pack.mjs from Simple Icons ${VERSION} (CC0: icons/SIMPLE-ICONS-LICENSE.txt). Do not edit.
// ${Object.keys(paths).length} brand icons for line bullets: slug -> SVG path (24x24, filled), display name and search words.
export const BRANDS = ${JSON.stringify(paths)};
export const BRAND_TITLES = ${JSON.stringify(titles)};
export const BRAND_WORDS = ${JSON.stringify(words)};
`;
fs.writeFileSync(path.join(ROOT, 'js', 'brand-pack.js'), out);
console.log(`wrote js/brand-pack.js: ${Object.keys(paths).length} brands, ${(out.length / 1024).toFixed(1)} KB`);
if (missing.length) console.log('not in this Simple Icons release (skipped): ' + missing.join(', '));
