#!/usr/bin/env node
// Builds js/icon-pack.js: the Lucide icons Linemark bundles for line bullets.
//
//   node tools/build-icon-pack.mjs            downloads the pinned Lucide release from jsDelivr
//   node tools/build-icon-pack.mjs <folder>   uses icon-nodes.json + tags.json already in <folder>
//
// Only the icons named in tools/icon-list.txt are bundled, so the extension stays small and works offline.
// Lucide is ISC-licensed; its licence ships as icons/LUCIDE-LICENSE.txt.

import fs from 'node:fs';
import path from 'node:path';

const VERSION = '0.460.0';
const ROOT = path.resolve(import.meta.dirname, '..');
const src = process.argv[2];

async function load(file) {
  if (src) return JSON.parse(fs.readFileSync(path.join(src, file), 'utf8'));
  const res = await fetch(`https://cdn.jsdelivr.net/npm/lucide-static@${VERSION}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return res.json();
}

const nodes = await load('icon-nodes.json');
const tags = await load('tags.json');
const wanted = fs.readFileSync(path.join(import.meta.dirname, 'icon-list.txt'), 'utf8')
  .split('\n').filter((l) => !l.trim().startsWith('#')).join(' ').split(/\s+/).filter(Boolean);

const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const toSvg = (list) => list.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');

const icons = {};
const words = {};
const missing = [];
for (const name of [...new Set(wanted)]) {
  if (!nodes[name]) { missing.push(name); continue; }
  icons[name] = toSvg(nodes[name]);
  words[name] = [name.replace(/-/g, ' '), ...(tags[name] || [])].join(' ').toLowerCase();
}

const out = `// Generated by tools/build-icon-pack.mjs from Lucide ${VERSION} (ISC licence: icons/LUCIDE-LICENSE.txt). Do not edit.
// ${Object.keys(icons).length} icons for line bullets: name -> SVG inner markup (24x24, stroke-based), plus search words.
export const ICONS = ${JSON.stringify(icons)};
export const ICON_WORDS = ${JSON.stringify(words)};
`;
fs.writeFileSync(path.join(ROOT, 'js', 'icon-pack.js'), out);
console.log(`wrote js/icon-pack.js: ${Object.keys(icons).length} icons, ${(out.length / 1024).toFixed(1)} KB`);
if (missing.length) console.log('not in this Lucide release (skipped): ' + missing.join(', '));
